public class CharcterInString {
    public static void main(String[] args) {
        String a = "sharan";
        char c = a.charAt(2); // Get the character at index 2
        char d = a.charAt(4); // Get the character at index 4

        System.out.println("The character at index 2 is: " + c); // Outputs 'a'
        System.out.println("The character at index 4 is: " + d); // Outputs 'a'
    }   
}
